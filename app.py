import json
from pathlib import Path
import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from src.data import CITIES, LOCALITIES, ensure_dataset, FEATURES
from src.predict import predict_price
from train import train

st.set_page_config(page_title="House Price Predictor", page_icon="🏡", layout="wide")
st.title("🏡 House Price Prediction")
st.caption("Enter property details to estimate a demo price. This project uses synthetic sample data for demonstration.")

df = ensure_dataset()
model_path = Path("models/house_price_model.joblib")
if not model_path.exists():
    with st.spinner("Preparing sample data and training the model for first use..."):
        train()

with st.sidebar:
    st.header("🏠 Property details")
    city = st.selectbox("City", CITIES, index=0)
    locality = st.selectbox("Area / locality", LOCALITIES, index=0)
    area_sqft = st.slider("Built-up area (sq.ft)", 400, 5000, 1200, 50)
    bedrooms = st.selectbox("Bedrooms (BHK)", [1, 2, 3, 4, 5, 6], index=2)
    bathrooms = st.selectbox("Bathrooms", [1, 2, 3, 4, 5, 6], index=1)
    balconies = st.selectbox("No. of balconies", [0, 1, 2, 3, 4], index=1)
    floor = st.number_input("Floor number", min_value=0, max_value=60, value=3)
    property_age = st.slider("Property age (years)", 0, 60, 5)
    parking = st.selectbox("Parking spaces", [0, 1, 2, 3], index=1)
    furnishing = st.selectbox("Furnishing", ["Unfurnished", "Semi-furnished", "Fully furnished"], index=1)
    gated_community = st.checkbox("Gated community", value=True)
    near_metro = st.checkbox("Near metro", value=False)
    predict_btn = st.button("Predict house price", type="primary", use_container_width=True)

payload = {
    "city": city, "locality": locality, "area_sqft": area_sqft, "bedrooms": bedrooms,
    "bathrooms": bathrooms, "balconies": balconies, "floor": floor, "property_age": property_age,
    "parking": parking, "furnishing": furnishing,
    "gated_community": int(gated_community), "near_metro": int(near_metro)
}
left, right = st.columns([1.25, 1])
with left:
    st.subheader("Your property")
    st.write(f"**{area_sqft:,} sq.ft · {bedrooms} BHK · {bathrooms} bathrooms**")
    st.write(f"**{locality}, {city}**")
    st.write(f"Balconies: {balconies} · Floor: {floor} · Age: {property_age} years")
    if predict_btn:
        price = predict_price(payload)
        st.success("Estimated demo price")
        st.metric("Estimated price", f"₹{price/100000:.2f} lakh")
        st.caption(f"Approx. ₹{price/10000000:.2f} crore. The estimate is generated by a machine-learning model trained on demo data.")
    else:
        st.info("Choose your details in the sidebar and click **Predict house price**.")

with right:
    st.subheader("Dataset overview")
    a, b, c = st.columns(3)
    a.metric("Demo records", f"{len(df):,}")
    b.metric("Input features", len(FEATURES))
    c.metric("Average demo price", f"₹{df['price_inr'].mean()/100000:.1f} L")
    st.caption("The sample data is synthetic; these figures are not actual market statistics.")

tab1, tab2, tab3 = st.tabs(["📊 Price distribution", "🔎 Compare features", "ℹ️ About the model"])
with tab1:
    fig, ax = plt.subplots(figsize=(8, 3.5))
    sns.histplot(df["price_inr"] / 100000, bins=30, kde=True, ax=ax)
    ax.set_xlabel("Demo price (₹ lakh)")
    ax.set_title("Distribution of sample prices")
    st.pyplot(fig)
    plt.close(fig)
with tab2:
    chosen = st.selectbox("Compare by", ["area_sqft", "bedrooms", "bathrooms", "property_age", "balconies"])
    fig, ax = plt.subplots(figsize=(8, 3.5))
    plot_df = df.sample(min(500, len(df)), random_state=42).copy()
    plot_df["price_lakh"] = plot_df["price_inr"] / 100000
    sns.scatterplot(data=plot_df, x=chosen, y="price_lakh", ax=ax, alpha=.5)
    ax.set_ylabel("Demo price (₹ lakh)")
    ax.set_title(f"{chosen.replace('_', ' ').title()} vs price")
    st.pyplot(fig)
    plt.close(fig)
with tab3:
    st.markdown("""
    - **Algorithm:** Random Forest Regressor
    - **Preprocessing:** missing-value imputation, scaling numeric features, one-hot encoding categories
    - **Evaluation:** MAE, RMSE and R² are saved to `models/metrics.json`
    - **Features:** city, locality, area, BHK, bathrooms, balconies, floor, age, parking, furnishing, gated community and metro access
    - **Disclaimer:** This is a learning project. Accuracy on generated data does not indicate accuracy on real property prices.
    """)
    metrics_path = Path("models/metrics.json")
    if metrics_path.exists():
        st.json(json.loads(metrics_path.read_text(encoding="utf-8")))
